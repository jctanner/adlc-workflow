"""Deterministic refinement trial checks."""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from .metrics import observed_models, prohibited_activity
from .records import read_json, sha256_file, write_json


def _headings(markdown: str) -> list[tuple[int, str, int]]:
    values = []
    fenced = False
    position = 0
    for line in markdown.splitlines(keepends=True):
        stripped = line.strip()
        if stripped.startswith("```") or stripped.startswith("~~~"):
            fenced = not fenced
        if not fenced:
            match = re.match(r"^(#{1,6})\s+(.+?)\s*$", line)
            if match:
                values.append((len(match.group(1)), match.group(2).strip(), position))
        position += len(line)
    return values


def _section(markdown: str, name: str, end_names: set[str]) -> str | None:
    headings = _headings(markdown)
    start = next((item for item in headings if item[1] == name), None)
    if not start:
        return None
    end = len(markdown)
    for level, title, position in headings:
        if position > start[2] and level <= start[0] and title in end_names:
            end = position
            break
    return markdown[start[2]:end]


def _result(identifier: str, passed: bool | None, detail: str) -> dict[str, Any]:
    return {"id": identifier, "status": "pass" if passed else "fail" if passed is False else "unknown", "detail": detail}


def check_trial(experiment_root: Path, trial_root: Path, candidate: dict[str, Any]) -> dict[str, Any]:
    workspace = trial_root / "workspace"
    input_dir = trial_root / "input"
    record_path = workspace / ".adlc-eval" / "container-result.json"
    results: list[dict[str, Any]] = []
    if not record_path.is_file():
        results.append(_result("completion_contract", False, "container did not write a result record"))
        return _finish(trial_root, results)
    record = read_json(record_path)
    success = record.get("status") == "succeeded"
    results.append(_result("completion_contract", success, record.get("error", "worker completed")))
    task = read_json(input_dir / "task.json")
    output = workspace / "artifacts" / "rhai-feature-tasks" / f"{task.get('issue_key')}.md"
    artifact_ok = success and output.is_file() and bool(output.read_text(encoding="utf-8").strip())
    results.append(_result("assigned_artifact", artifact_ok, str(output)))
    content = output.read_text(encoding="utf-8") if artifact_ok else ""
    required = ("Strategy (AI Generated by Agentic SDLC Pipeline)", "TL;DR", "Technical Approach", "Acceptance Criteria", "Staff Engineer / SME Input")
    headings = {title for _, title, _ in _headings(content)}
    results.append(_result("template_sections", all(item in headings for item in required),
                           "missing: " + ", ".join(item for item in required if item not in headings)))
    request = read_json(input_dir / "request.json")
    source = request.get("kwargs", {}).get("source_issues", {}).get(task.get("issue_key"), {})
    fields = source.get("fields", {}) if isinstance(source, dict) else {}
    business = _section(content, "Business Need", {"Strategy (AI Generated by Agentic SDLC Pipeline)", "Staff Engineer / SME Input"})
    expected = [fields.get("summary"), fields.get("description")]
    normalized = (business or "").replace("\r\n", "\n")
    preserved = all(isinstance(value, str) and value.replace("\r\n", "\n").strip() in normalized for value in expected)
    results.append(_result("source_preservation", preserved, "Business Need preserves supplied summary and description"))
    prompt = workspace / ".adlc-eval" / "prompt.txt"
    frozen = prompt.is_file() and sha256_file(prompt) == record.get("prompt_sha256")
    results.append(_result("frozen_inputs", frozen, "prompt hash matches execution record"))
    event_path = workspace / ".adlc-eval" / "events.jsonl"
    observed = observed_models(event_path)
    accepted = set(candidate.get("accepted_resolved_models", []))
    model_ok = bool(observed) and set(observed).issubset(accepted)
    results.append(_result("model_identity", model_ok, f"observed={observed}, accepted={sorted(accepted)}"))
    forbidden = prohibited_activity(event_path)
    results.append(_result("bounded_worker", not forbidden, "violations=" + repr(forbidden)))
    return _finish(trial_root, results)


def _finish(trial_root: Path, values: list[dict[str, Any]]) -> dict[str, Any]:
    result = {"schema_version": 1, "checks": values, "eligible": all(item["status"] == "pass" for item in values)}
    write_json(trial_root / "checks.json", result)
    return result
